import math

num = float(input("Enter a Floating number: "))

sqrt = math.sqrt(num)

power = num ** 4

floor = math.floor(num)

print(f"Square root of the number is: {sqrt}")
print(f"Fourth power of the number is: {power}")
print(f"Floor of the number is: {floor}")

